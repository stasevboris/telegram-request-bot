    """Ищет автоответ по базе знаний по ключевым корням слов."""
    t = text.lower()
    for entry in KNOWLEDGE_BASE:
        for kw in entry["keywords"]:
            if kw in t:
                return entry["topic"], entry["answer"]
    return None

